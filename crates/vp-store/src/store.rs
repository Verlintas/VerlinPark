/// Event payloads and projection rows are bounded. A cached result still
/// carries its status, exit code, warnings, and failure count even when the
/// structured preview was clipped; the full body remains behind `output_ref`.
fn bounded_test_result_preview(result_json: &str) -> String {
    const MAX_PREVIEW_BYTES: usize = 8 * 1024;
    if result_json.len() <= MAX_PREVIEW_BYTES {
        return result_json.to_string();
    }
    let mut end = MAX_PREVIEW_BYTES;
    while end > 0 && !result_json.is_char_boundary(end) {
        end -= 1;
    }
    format!(
        "{}… (cached structured result truncated at {MAX_PREVIEW_BYTES} bytes)",
        &result_json[..end]
    )
}

fn escape_like(query: &str) -> String {
    query
        .replace('\\', "\\\\")
        .replace('%', "\\%")
        .replace('_', "\\_")
}

fn search_snippet(text: &str, query: &str) -> String {
    let lower = text.to_lowercase();
    let needle = query
        .split_whitespace()
        .map(str::to_lowercase)
        .find(|term| !term.is_empty() && lower.contains(term))
        .unwrap_or_else(|| query.to_lowercase());
    let start = lower.find(&needle).unwrap_or(0);
    let char_start = lower[..start].chars().count();
    let chars = text.chars().collect::<Vec<_>>();
    let from = char_start.saturating_sub(60).min(chars.len());
    let to = (char_start + needle.chars().count() + 120).min(chars.len());
    let mut snippet = chars[from..to]
        .iter()
        .collect::<String>()
        .replace(['\n', '\r', '\t'], " ");
    if from > 0 {
        snippet.insert(0, '…');
    }
    if to < chars.len() {
        snippet.push('…');
    }
    snippet
}

