fn validate_imported_event_seq(kind: &str, label: &str, seq: u64) -> Result<()> {
    if seq == 0 || seq > i64::MAX as u64 {
        return Err(anyhow!(
            "bundle {kind} {label} has seq {seq}, outside 1..={}",
            i64::MAX
        ));
    }
    Ok(())
}

fn validate_imported_event_payload(kind: &str, label: &str, payload: &Value) -> Result<()> {
    let encoded = serde_json::to_vec(payload)
        .with_context(|| format!("serializing bundle {kind} {label} payload"))?;
    if encoded.len() > MAX_IMPORTED_EVENT_PAYLOAD_BYTES {
        return Err(anyhow!(
            "bundle {kind} {label} payload is {} bytes; the limit is {} bytes",
            encoded.len(),
            MAX_IMPORTED_EVENT_PAYLOAD_BYTES
        ));
    }
    Ok(())
}

