fn is_constraint_violation(error: &anyhow::Error) -> bool {
    error.chain().any(|cause| {
        matches!(
            cause.downcast_ref::<rusqlite::Error>(),
            Some(rusqlite::Error::SqliteFailure(inner, _))
                if inner.code == rusqlite::ErrorCode::ConstraintViolation
        )
    })
}

