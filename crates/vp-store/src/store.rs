/// Read the latest project snapshot for each project from `projects.jsonl`.
///
/// Malformed lines, explicit truncation markers, and legacy bounded snapshots
/// are hard errors: a rebuild must not silently use an older or partial
/// manifest as authoritative state.
pub fn read_project_manifest(data_dir: &Path) -> Result<Vec<ProjectManifestSnapshot>> {
    let path = data_dir.join("projects.jsonl");
    let file = match std::fs::File::open(&path) {
        Ok(file) => file,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => {
            return Err(error)
                .with_context(|| format!("opening project manifest {}", path.display()));
        }
    };
    let mut latest: std::collections::HashMap<String, ProjectManifestSnapshot> =
        std::collections::HashMap::new();
    for (index, line) in BufReader::new(file).lines().enumerate() {
        let line_number = index + 1;
        let line = line.with_context(|| {
            format!(
                "reading project manifest {} line {line_number}",
                path.display()
            )
        })?;
        if line.trim().is_empty() {
            continue;
        }
        let snapshot: ProjectManifestSnapshot = serde_json::from_str(&line).with_context(|| {
            format!(
                "parsing project manifest {} line {line_number}; the manifest may be truncated or corrupt",
                path.display()
            )
        })?;
        if snapshot.truncated {
            return Err(anyhow!(
                "project manifest {} line {line_number} for project {} is marked truncated; \
                 refusing to rebuild from an incomplete event stream",
                path.display(),
                snapshot.project.id
            ));
        }
        if snapshot.version < PROJECT_MANIFEST_VERSION {
            let capped_streams = [
                snapshot.agent_identity_events.len(),
                snapshot.agent_coordination_events.len(),
                snapshot.agent_workspace_events.len(),
                snapshot.agent_memory_events.len(),
                snapshot.agent_employment_events.len(),
                snapshot.program_events.len(),
                snapshot.team_template_events.len(),
            ];
            if capped_streams
                .iter()
                .any(|count| *count >= LEGACY_PROJECT_MANIFEST_EVENT_CAP)
            {
                return Err(anyhow!(
                    "project manifest {} line {line_number} for project {} was written by a \
                     bounded v{} reader and may be missing the newest events; re-record the \
                     manifest with the current build before rebuilding",
                    path.display(),
                    snapshot.project.id,
                    snapshot.version
                ));
            }
        }
        latest.insert(snapshot.project.id.clone(), snapshot);
    }
    let mut snapshots = latest.into_values().collect::<Vec<_>>();
    snapshots.sort_by(|left, right| left.project.created_at.cmp(&right.project.created_at));
    Ok(snapshots)
}

